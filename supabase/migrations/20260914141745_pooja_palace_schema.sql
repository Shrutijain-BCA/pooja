-- ============================================================
-- BOOKING NUMBER GENERATION
-- ============================================================
CREATE OR REPLACE FUNCTION generate_booking_number()
RETURNS text AS $$
DECLARE
  current_year int := EXTRACT(YEAR FROM now());
  next_num int;
  booking_num text;
BEGIN
  SELECT COALESCE(MAX(num_seq), 0) + 1 INTO next_num
  FROM (
    SELECT
      CAST(
        SUBSTRING(booking_number FROM POSITION('-' IN booking_number) + 1 FOR LENGTH(booking_number) - POSITION('-' IN booking_number) - POSITION('-' IN REVERSE(booking_number)) + 2)
        AS int
      ) AS num_seq
    FROM bookings
    WHERE booking_number LIKE 'PP-' || current_year || '-%'
      AND booking_number ~ '^PP-[0-9]{4}-[0-9]{5}$'
  ) sub;

  booking_num := 'PP-' || current_year || '-' || lpad(next_num::text, 5, '0');
  RETURN booking_num;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger to auto-generate booking number on insert
CREATE OR REPLACE FUNCTION set_booking_number()
RETURNS trigger AS $$
BEGIN
  IF NEW.booking_number IS NULL OR NEW.booking_number = '' THEN
    NEW.booking_number := generate_booking_number();
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trigger_set_booking_number ON bookings;
CREATE TRIGGER trigger_set_booking_number
  BEFORE INSERT ON bookings
  FOR EACH ROW EXECUTE FUNCTION set_booking_number();

