/*
# Pooja Palace — Complete Database Schema

## Overview
Creates the full schema for a Hindu spiritual and Vedic pooja booking platform where users discover and book poojas at sacred destinations across India. Same pooja can have different prices at different locations via a location_poojas offering table.

## New Tables (11 total)

1. **user_profiles** — Extended user info linked to auth.users (name, phone, profile image)
2. **states** — Indian states (Uttarakhand, Uttar Pradesh, etc.)
3. **locations** — Destinations/cities/religious places, hierarchical (state → location → sub-location)
4. **categories** — Pooja categories (Pooja, Havan, Jap, Path, Shanti/Dosha, etc.)
5. **purposes** — Why a pooja is performed (New Home, Marriage, Pitri/Ancestors, etc.)
6. **deities** — Hindu deities (Shiva, Vishnu, Ganesh, Durga, Lakshmi, etc.)
7. **occasions** — Life events (New Home, Marriage, Child, Navratri, etc.)
8. **poojas** — Master pooja records with category/purpose/deity/occasion relationships
9. **location_poojas** — Location-specific offerings (price, duration, availability per location per pooja)
10. **bookings** — Booking requests with status workflow (PENDING → CONFIRMED → COMPLETED / CANCELLED)
11. **notifications** — User notifications for booking status changes

## Junction Tables
- pooja_categories, pooja_purposes, pooja_deities, pooja_occasions — many-to-many relationships

## Security
- RLS enabled on ALL tables
- Public data (states, locations, categories, purposes, deities, occasions, poojas, location_poojas) → readable by anon + authenticated
- User-specific data (user_profiles, bookings, notifications) → owner-scoped (authenticated, auth.uid() = user_id)
- Admin data (write operations on all tables) → managed via service role key from edge functions, or admin RLS via app metadata
- Booking number auto-generated via database function + trigger (PP-YYYY-NNNNN format)

## Important Notes
1. user_profiles.user_id defaults to auth.uid() so inserts work without explicitly passing user_id
2. bookings.user_id defaults to auth.uid() for the same reason
3. bookings.booking_number auto-generated by trigger using generate_booking_number() function
4. All foreign keys use ON DELETE RESTRICT on poojas/locations to preserve historical booking integrity
5. location_poojas has a unique constraint on (location_id, pooja_id) to prevent duplicate offerings
6. Admin access is controlled via raw_app_meta_data ->> 'role' = 'admin' check in RLS policies
*/

