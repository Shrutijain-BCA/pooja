-- ============================================================
-- HELPER: Create notification when booking status changes
-- ============================================================
CREATE OR REPLACE FUNCTION create_booking_notification()
RETURNS trigger AS $$
DECLARE
  notif_title text;
  notif_message text;
  notif_type text;
BEGIN
  IF (TG_OP = 'UPDATE' AND NEW.status IS DISTINCT FROM OLD.status) THEN
    notif_type := 'booking_status_change';

    IF NEW.status = 'CONFIRMED' THEN
      notif_title := 'Booking Confirmed';
      notif_message := 'Your booking ' || NEW.booking_number || ' has been confirmed. Our team will contact you with further details.';
    ELSIF NEW.status = 'CANCELLED' THEN
      notif_title := 'Booking Cancelled';
      notif_message := COALESCE(NEW.cancellation_reason, 'Your booking ' || NEW.booking_number || ' has been cancelled.');
      IF NEW.cancellation_reason IS NOT NULL AND NEW.cancellation_reason != '' THEN
        notif_message := 'Your booking ' || NEW.booking_number || ' has been cancelled. Reason: ' || NEW.cancellation_reason;
      END IF;
    ELSIF NEW.status = 'COMPLETED' THEN
      notif_title := 'Pooja Completed';
      notif_message := 'Your booking ' || NEW.booking_number || ' has been marked as completed. Thank you for choosing Pooja Palace.';
    ELSE
      notif_title := 'Booking Updated';
      notif_message := 'Your booking ' || NEW.booking_number || ' status has been updated to ' || NEW.status || '.';
    END IF;

    INSERT INTO notifications (user_id, booking_id, type, title, message)
    VALUES (NEW.user_id, NEW.id, notif_type, notif_title, notif_message);
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trigger_booking_notification ON bookings;
CREATE TRIGGER trigger_booking_notification
  AFTER UPDATE ON bookings
  FOR EACH ROW EXECUTE FUNCTION create_booking_notification();

-- ============================================================
-- HELPER: Auto-create user profile on signup
-- ============================================================
